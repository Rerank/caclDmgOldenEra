/**
 * Проверка перед публикацией на GitHub Pages. Запускается из predeploy.
 *
 * gh-pages публикует локальную папку dist, а не коммит. Без этой проверки
 * на сайт могли бы уехать незакоммиченные правки — и опубликованная версия
 * не совпадала бы ни с одним коммитом в истории.
 */
import { execSync } from 'node:child_process'

/** Выполняет git-команду и возвращает её вывод как строку. */
const git = (args) => execSync(`git ${args}`, { encoding: 'utf8' })

/** Печатает причину отказа и завершает процесс с ошибкой — npm остановит цепочку. */
function fail(message) {
  console.error(`\nПубликация отменена: ${message}\n`)
  process.exit(1)
}

// Публикуем только из main: в других ветках живёт незаконченная работа
const branch = git('rev-parse --abbrev-ref HEAD').trim()
if (branch !== 'main') {
  fail(`текущая ветка «${branch}», публиковать можно только из main.`)
}

// --porcelain — стабильный формат для скриптов: пустой вывод значит «всё закоммичено».
// Новые файлы (??) тоже считаются: если их импортирует код, они попадут в сборку.
// core.quotepath=false — чтобы имена с кириллицей печатались как есть, а не \320\241…
const changes = git('-c core.quotepath=false status --porcelain').trimEnd()
if (changes) {
  fail(`есть незакоммиченные изменения:\n\n${changes}\n\nЗакоммить их и запусти публикацию снова.`)
}

console.log('Всё закоммичено, ветка main — можно публиковать.')